export function getTranslatedProduct(
  product: { id: string; name: string; description: string },
  lang: SupportedLang
): { name: string; description: string } {
  if (lang === 'tr') {
    return { name: product.name, description: product.description };
  }
  const entry = PRODUCT_I18N[product.id];
  if (entry) {
    const localized = entry[lang] || entry.en;
    if (localized) return localized;
  }
  return { name: product.name, description: product.description };
}

export function getTranslatedCategoryName(
  category: { id: string; name: string },
  lang: SupportedLang
): string {
  const dict = TRANSLATIONS[lang];
  return dict.categories.names[category.id] || category.name;
}
